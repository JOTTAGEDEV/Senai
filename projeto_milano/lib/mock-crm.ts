let seq = 0;
function msg(leadId: string, autor: Mensagem["autor"], minutosAtras: number, texto: string, autorNome = ""): Mensagem {
  seq += 1;
  return {
    id: `msg-${leadId}-${seq}`,
    leadId,
    autor,
    autorNome: autorNome || (autor === "ia" ? "Assistente IA" : autor === "cliente" ? "" : "Vendedor"),
    texto,
    midiaUrl: null,
    criadaEm: minAtras(minutosAtras),
  };
}

