import { veiculoVazio } from "./constants";
import type { Veiculo, VeiculoInput } from "./types";

function diasAtras(n: number): string {
  const d = new Date();
  d.setDate(d.getDate() - n);
  return d.toISOString().slice(0, 10);
}

function carro(id: string, dados: Partial<VeiculoInput>): Veiculo {
  const base = veiculoVazio();
  const agora = new Date().toISOString();
  return {
    ...base,
    ...dados,
    checklist: { ...base.checklist, ...dados.checklist },
    links: { ...base.links, ...dados.links },
    id,
    criadoEm: agora,
    atualizadoEm: agora,
  };
}

